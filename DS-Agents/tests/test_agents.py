def answer():
    return {"summary": "静态分析", "claims": [{"id": "a", "statement": "空列表会除以零。", "stance": "supported",
            "evidence": [{"path": "sample.py", "line_start": 2, "line_end": 2,
                          "quote": "    return sum(values) / len(values)"}], "reason": "分母可能为零。"}],
            "questions": [], "responses": [], "limitations": ["没有运行代码。"]}


class RecordingProvider:
    def __init__(self, name, fail=False):
        self.name, self.role, self.fail = name, "测试角色", fail
        self.prompts = []

    def preflight(self):
        pass

    def generate(self, prompt, call_dir):
        self.prompts.append(json.loads(prompt))
        if self.fail:
            raise AgentError("故障注入")
        return Reply(answer(), 20, 10, "fixture")


class Case(unittest.TestCase):
    def setUp(self):
        base = Path(__file__).resolve().parents[1] / ".test-tmp"
        base.mkdir(exist_ok=True)
        self.temp = tempfile.TemporaryDirectory(dir=base)
        self.root = Path(self.temp.name)
        self.project = self.root / "project"
        self.project.mkdir()
        (self.project / "sample.py").write_text("def average(values):\n    return sum(values) / len(values)\n", encoding="utf-8")
        self.config = copy.deepcopy(DEFAULT)

    def tearDown(self):
        self.temp.cleanup()

    def test_snapshot_excludes_credentials_and_redacts_inline(self):
        (self.project / ".env").write_text("KEY=DO_NOT_SEND")
        (self.project / "credentials.json").write_text('{"secret": "DO_NOT_SEND"}')
        (self.project / "settings.py").write_text('api_key = "sk-123456' + '7890abcdefghijkl"\nprint("ok")\n')
        snapshot = collect(self.project, self.config["snapshot"], Redactor())
        self.assertEqual(set(snapshot.files), {"sample.py", "settings.py"})
        self.assertNotIn("sk-123456", snapshot.files["settings.py"])
        self.assertEqual(len(snapshot.files["settings.py"].splitlines()), 2)

    def test_output_in_source_rejected_before_write(self):
        with self.assertRaises(AgentError):
            safe_output(self.project, self.project / "new-output")
        self.assertFalse((self.project / "new-output").exists())

    def test_symlink_outside_source_is_never_read(self):
        outside = self.root / "outside.py"
        outside.write_text("SENSITIVE_OUTSIDE")
        try:
            (self.project / "link.py").symlink_to(outside)
        except OSError:
            self.skipTest("OS account cannot create symlinks; junction test covers Windows directory links")
        snapshot = collect(self.project, self.config["snapshot"], Redactor())
        self.assertNotIn("link.py", snapshot.files)

    @unittest.skipUnless(os.name == "nt", "Windows junction only")
    def test_windows_junction_is_never_followed(self):
        outside = self.root / "outside"
        outside.mkdir()
        (outside / "other.py").write_text("SENSITIVE_OUTSIDE")
        junction = self.project / "linked"
        # Fixed test paths generated by tempfile, no user supplied shell arguments.
        command = f'New-Item -ItemType Junction -Path \'{junction}\' -Target \'{outside}\' | Out-Null'
        result = subprocess.run(["powershell.exe", "-NoProfile", "-Command", command], capture_output=True)
        self.assertEqual(result.returncode, 0)
        try:
            snapshot = collect(self.project, self.config["snapshot"], Redactor())
            self.assertEqual(set(snapshot.files), {"sample.py"})
            with self.assertRaises(AgentError):
                safe_output(junction, self.root / "out")
        finally:
            # Removes only the junction itself, never recurses into its target.
            os.rmdir(junction)
        self.assertTrue((outside / "other.py").exists())

    def test_hardlink_excluded(self):
        path = self.project / "hard.py"
        os.link(self.project / "sample.py", path)
        (self.project / "README.md").write_text("safe")
        snapshot = collect(self.project, self.config["snapshot"], Redactor())
        self.assertEqual(set(snapshot.files), {"README.md"})

    def test_snapshot_limits_and_explicit_includes(self):
        (self.project / "large.py").write_text("x" * 200)
        self.config["snapshot"]["max_file_bytes"] = 100
        snapshot = collect(self.project, self.config["snapshot"], Redactor())
        self.assertEqual(set(snapshot.files), {"sample.py"})
        self.assertEqual(snapshot.skipped[0]["reason"], "file-too-large")

    def test_invalid_evidence_cannot_become_verified(self):
        item = answer()
        files = {"sample.py": (self.project / "sample.py").read_text()}
        self.assertTrue(verify(item, files)[0]["all_references_match"])
        for path, start, quote in [("../secret.txt", 2, "x"), ("sample.py", 100, "x"), ("sample.py", 2, "invented")]:
            item["claims"][0]["evidence"][0].update(path=path, line_start=start, quote=quote)
            self.assertFalse(verify(item, files)[0]["all_references_match"])

    def test_protocol_rejects_malformed_and_unknown_fields(self):
        for value in ("not json", '{"summary":"x"}', json.dumps({**answer(), "execute": "danger"})):
            with self.assertRaises(AgentError):
                parse_answer(value)

    def test_round_barrier_exchange_and_source_unchanged(self):
        before = (self.project / "sample.py").read_bytes()
        a, b = RecordingProvider("codex"), RecordingProvider("deepseek")
        run_dir, result = run_analysis(self.project, self.root / "out", "检查边界", self.config, [a, b], mock=True)
        self.assertEqual(result["status"], "completed")
        self.assertEqual(len(result["turns"]), 4)
        self.assertEqual(a.prompts[0]["previous_round"], [])
        self.assertEqual(b.prompts[0]["previous_round"], [])
        self.assertEqual(a.prompts[1]["previous_round"], b.prompts[1]["previous_round"])
        self.assertEqual({x["provider"] for x in a.prompts[1]["previous_round"]}, {"codex", "deepseek"})
        self.assertEqual(before, (self.project / "sample.py").read_bytes())
        self.assertEqual(list(self.project.iterdir()), [self.project / "sample.py"])
        self.assertTrue((run_dir / "report.md").exists())
        self.assertEqual(json.loads((run_dir / "events.jsonl").read_text().splitlines()[-1])["type"], "finished")

    def test_failure_keeps_partial_results_and_never_retries(self):
        a, b = RecordingProvider("codex"), RecordingProvider("deepseek", fail=True)
        run_dir, result = run_analysis(self.project, self.root / "out", "分析", self.config, [a, b], mock=True)
        self.assertEqual(result["status"], "failed")
        self.assertEqual(len(result["turns"]), 1)
        self.assertEqual(len(b.prompts), 1)
        self.assertTrue((run_dir / "report.md").exists())

    def test_missing_deepseek_key_prevents_any_codex_call(self):
        a = RecordingProvider("codex")
        with patch.dict(os.environ, {}, clear=True):
            with self.assertRaisesRegex(AgentError, "DEEPSEEK_API_KEY"):
                run_analysis(self.project, self.root / "out", "分析", self.config, [a, DeepSeekProvider(self.config)])
        self.assertEqual(a.prompts, [])
        self.assertFalse((self.root / "out").exists())

    def test_preview_never_calls_provider(self):
        a, b = RecordingProvider("codex", True), RecordingProvider("deepseek", True)
        run_dir, result = run_analysis(self.project, self.root / "out", "分析", self.config, [a, b], preview=True)
        self.assertEqual(result["status"], "preview")
        self.assertEqual(a.prompts + b.prompts, [])
        self.assertTrue((run_dir / "snapshot.json").exists())

    def test_cancellation_saves_partial_report(self):
        class Cancelled(RecordingProvider):
            def generate(self, prompt, call_dir):
                raise KeyboardInterrupt()
        run_dir, result = run_analysis(self.project, self.root / "out", "分析", self.config,
                                      [RecordingProvider("codex"), Cancelled("deepseek")], mock=True)
        self.assertEqual(result["status"], "interrupted")
        self.assertEqual(len(result["turns"]), 1)
        self.assertTrue((run_dir / "report.md").exists())

    def test_post_call_token_overrun_stops_before_next_provider(self):
        self.config["max_total_tokens"] = 1
        a, b = RecordingProvider("codex"), RecordingProvider("deepseek")
        _, result = run_analysis(self.project, self.root / "out", "分析", self.config, [a, b], mock=True)
        self.assertEqual(result["status"], "failed")
        self.assertEqual(len(result["turns"]), 1)
        self.assertEqual(b.prompts, [])

    def test_hash_check_detects_file_growth_without_unbounded_read(self):
        snapshot = collect(self.project, self.config["snapshot"], Redactor())
        (self.project / "sample.py").write_text("x" * 400000)
        self.assertEqual(snapshot.changed_files(), ["sample.py"])

    def test_budget_rejects_before_network_and_counts_failed_reservations(self):
        self.config["deepseek"]["max_usd"] = 0.000001
        budget = Budget(self.config)
        with self.assertRaises(AgentError):
            budget.reserve("deepseek", "hello")
        self.assertEqual(budget.calls, 0)
        budget.reserve("codex", "hello")
        self.assertEqual(budget.codex_calls, 1)
        budget.tokens = self.config["max_total_tokens"]
        with self.assertRaises(AgentError):
            budget.reserve("codex", "hello")

    def test_config_validation_rejects_negative_nan_unknown_and_bool(self):
        for data in ({"rounds": -1}, {"rounds": True}, {"rounds": 6}, {"unknown": 3}, {"deepseek": {"max_usd": float("nan")}}):
            config = self.root / "bad.json"
            config.write_text(json.dumps(data))
            with self.assertRaises(AgentError):
                load_config(config)

    def test_deepseek_payload_and_usage_parsing(self):
        received = []
        def transport(body, key, timeout, cap):
            received.append(body)
            self.assertEqual(key, "test-key")
            return {"choices": [{"finish_reason": "stop", "message": {"content": json.dumps(answer())}}],
                    "usage": {"prompt_tokens": 123, "completion_tokens": 45}, "model": "test-model"}
        with patch.dict(os.environ, {"DEEPSEEK_API_KEY": "test-key"}):
            reply = DeepSeekProvider(self.config, transport).generate("question", self.root)
        self.assertEqual(reply.input_tokens, 123)
        self.assertNotIn("tools", received[0])
        self.assertEqual(received[0]["thinking"], {"type": "disabled"})
        self.assertEqual(received[0]["response_format"], {"type": "json_object"})
        self.assertNotIn("test-key", json.dumps(received))

    def test_deepseek_rejects_truncation_and_missing_usage(self):
        with patch.dict(os.environ, {"DEEPSEEK_API_KEY": "test-key"}):
            for finish in ("length", "stop"):
                transport = lambda *a: {"choices": [{"finish_reason": finish, "message": {"content": json.dumps(answer())}}]}
                with self.assertRaises(AgentError):
                    DeepSeekProvider(self.config, transport).generate("question", self.root)

    def test_http_error_does_not_leak_response_or_key(self):
        with patch("ds_agents.providers.http.client.HTTPSConnection") as connection:
            connection.return_value.getresponse.return_value.status = 401
            with self.assertRaisesRegex(AgentError, "HTTP 401") as error:
                deepseek_post({}, "do-not-log-this", 5, 1000)
            self.assertNotIn("do-not-log-this", str(error.exception))
            connection.return_value.getresponse.return_value.read1.assert_not_called()

    def test_codex_jsonl_complete_parse_and_safety_arguments(self):
        provider = CodexProvider(self.config)
        provider.executable = "codex.exe"
        output = "\n".join(json.dumps(e) for e in [
            {"type": "item.completed", "item": {"type": "agent_message", "text": json.dumps(answer())}},
            {"type": "turn.completed", "usage": {"input_tokens": 10, "output_tokens": 20}}])
        with patch("ds_agents.providers.bounded_process", return_value=(0, output, "")) as process:
            reply = provider.generate("question", self.root)
        args = process.call_args.args[0]
        self.assertIn("read-only", args)
        self.assertIn("--ignore-user-config", args)
        self.assertIn("shell_tool", args)
        self.assertNotIn("danger-full-access", args)
        self.assertEqual(reply.output_tokens, 20)
        self.assertEqual(process.call_args.args[1], self.root)

    def test_codex_rejects_failed_event_and_tool_use(self):
        provider = CodexProvider(self.config)
        provider.executable = "codex.exe"
        for event in ({"type": "turn.failed"}, {"type": "item.completed", "item": {"type": "file_change"}}):
            with patch("ds_agents.providers.bounded_process", return_value=(0, json.dumps(event), "")):
                with self.assertRaises(AgentError):
                    provider.generate("question", self.root)

    def test_secret_redaction_in_question_and_persisted_model_reply(self):
        class Echo(RecordingProvider):
            def generate(self, prompt, call_dir):
                result = answer()
                result["summary"] = "private-test-secret"
                return Reply(result, 1, 1, "fixture")
        with patch.dict(os.environ, {"DEEPSEEK_API_KEY": "private-test-secret"}):
            run_dir, result = run_analysis(self.project, self.root / "out", "private-test-secret", self.config,
                                          [Echo("codex"), Echo("deepseek")], mock=True)
        for file in run_dir.glob("*.*"):
            self.assertNotIn("private-test-secret", file.read_text(encoding="utf-8"))

    def test_process_timeout_and_output_cap(self):
        with self.assertRaisesRegex(AgentError, "超时"):
            bounded_process([sys.executable, "-c", "import time; time.sleep(30)"], self.root, os.environ.copy(), "", 0.2, 10000)
        with self.assertRaisesRegex(AgentError, "大小限制"):
            bounded_process([sys.executable, "-c", "print('x'*100000)"], self.root, os.environ.copy(), "", 5, 1000)


